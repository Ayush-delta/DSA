#include <iostream> 
using namespace std;

int main() {
    int a = 10;
    int b = 20;
    cout << "the value of a > b "<< (a>b) << endl;
    cout << "the value of a < b "<< (a<b) << endl;
    cout << "the value of a == b "<< (a==b) << endl;
    cout << "the value of a != b "<< (a!=b) << endl;
    cout << "the value of a >= b "<< (a>=b) << endl;
    cout << "the value of a <= b "<< (a<=b) << endl;
    return 0;
}